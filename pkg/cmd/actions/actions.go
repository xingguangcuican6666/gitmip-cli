package actions

import (
	"github.com/MakeNowJust/heredoc"
	"github.com/cli/cli/v2/pkg/cmdutil"
	"github.com/cli/cli/v2/pkg/iostreams"
	"github.com/spf13/cobra"
)

func NewCmdActions(f *cmdutil.Factory) *cobra.Command {
	cs := f.IOStreams.ColorScheme()

	cmd := &cobra.Command{
		Use:    "actions",
		Short:  "Learn about working with GitHub Actions",
		Long:   actionsExplainer(cs),
		Hidden: true,
	}

	cmdutil.DisableAuthCheck(cmd)

	return cmd
}

func actionsExplainer(cs *iostreams.ColorScheme) string {
	header := cs.Bold("Welcome to GitHub Actions on the command line.")
	runHeader := cs.Bold("Interacting with workflow runs")
	workflowHeader := cs.Bold("Interacting with workflow files")
	cacheHeader := cs.Bold("Interacting with the GitHub Actions cache")

	return heredoc.Docf(`
			%[2]s

			GitHub CLI integrates with GitHub Actions to help you manage runs and workflows.

			%[3]s
			gm run list:      List recent workflow runs
			gm run view:      View details for a workflow run or one of its jobs
			gm run watch:     Watch a workflow run while it executes
			gm run rerun:     Rerun a failed workflow run
			gm run download:  Download artifacts generated by runs

			To see more help, run %[1]sgm help run <subcommand>%[1]s

			%[4]s
			gm workflow list:     List workflow files in your repository
			gm workflow view:     View details for a workflow file
			gm workflow enable:   Enable a workflow file
			gm workflow disable:  Disable a workflow file
			gm workflow run:      Trigger a workflow_dispatch run for a workflow file

			To see more help, run %[1]sgm help workflow <subcommand>%[1]s

			%[5]s
			gm cache list:    List all the caches saved in GitHub Actions for a repository
			gm cache delete:  Delete one or all saved caches in GitHub Actions for a repository

			To see more help, run %[1]sgm help cache <subcommand>%[1]s

		`, "`", header, runHeader, workflowHeader, cacheHeader)
}
